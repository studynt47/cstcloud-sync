import "dotenv/config";
import esbuild from "esbuild";
import process from "process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

console.log(`esbuild version = ${esbuild.version}`);

const prod = process.argv[2] === "production";

// cstcloud-sync: only S3 is supported, no OAuth env vars needed (Step 30)
esbuild
  .context({
    banner: {
      js: banner,
    },
    loader: {
      ".svg": "text",
    },
    entryPoints: ["./src/main.ts"],
    bundle: true,
    external: [
      "obsidian",
      "electron",
      "fs",
      "tls",
      "net",
      "http",
      "https",
      "vm",
      "node:url",
      "node:path",
      "node:fs",
    ],
    // Force browser platform (Obsidian is browser-based)
    platform: "browser",
    inject: ["./esbuild.injecthelper.mjs"],
    format: "cjs",
    target: "es2020",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    minify: prod,
    outfile: "main.js",
    define: {
      global: "window",
      "process.env.NODE_DEBUG": `undefined`,
      "process.env.DEBUG": `undefined`,
      "globalThis.process.versions": `undefined`,
    },
  })
  .then((context) => {
    if (process.argv.includes("--watch")) {
      context.watch();
    } else {
      context.rebuild().then((result) => {
        context.dispose();
      });
    }
  })
  .catch(() => process.exit(1));
